from datetime import UTC

from django.utils.dateparse import parse_datetime
from rest_framework import serializers

from assessments.models import TransferType
from common.validators import validate_iranian_iban

MAX_INT64 = 9_223_372_036_854_775_807


class StrictPositiveInt64Field(serializers.IntegerField):
    """
    Custom DRF field enforcing 64 Integer Rules
    """

    class StrictPositiveInt64Field(serializers.IntegerField):
        def __init__(self, **kwargs):
            kwargs.setdefault("min_value", 1)
            kwargs.setdefault("max_value", MAX_INT64)
            super().__init__(**kwargs)

    def to_internal_value(self, data):
        if isinstance(data, bool) or not isinstance(data, int):
            self.fail("invalid")

        value = super().to_internal_value(data)

        if value <= 0:
            raise serializers.ValidationError("Amount must be a strictly positive integer in IRR.")
        if value > MAX_INT64:
            raise serializers.ValidationError("Amount exceeds maximum 64-bit integer limit")

        return value


class RiskAssessmentRequestSerializer(serializers.Serializer):
    """
    Input contract for POST /api/v1/risk-assessments (Section 6).
    Enforces strict int64 positive IRR amounts and conditional destination fields based on `transfer_type`.
    """

    transaction_id = serializers.UUIDField(help_text="Unique transaction UUID generated by S3-PAY.")
    transfer_type = serializers.ChoiceField(
        choices=TransferType.choices,
        help_text="INTERNAL (uses destination_account_id) or EXTERNAL (uses destination_iban).",
    )
    source_account_id = serializers.UUIDField(
        help_text="UUID of the sender's LabBank account (shared with S1 and S2; used by S4 to query S2 ledger history)."
    )
    destination_account_id = serializers.UUIDField(
        required=False,
        allow_null=True,
        default=None,
        help_text="Required when `transfer_type` is `INTERNAL` (must differ from `source_account_id`). Must be null or omitted when `transfer_type` is `EXTERNAL`.",  # noqa: E501
    )
    destination_iban = serializers.CharField(
        max_length=26,
        min_length=26,
        required=False,
        allow_null=True,
        default=None,
        validators=[validate_iranian_iban],
        help_text="Required when `transfer_type` is `EXTERNAL` (IR + 24 ASCII digits with valid ISO 13616 Mod-97 checksum). Must be null or omitted when `transfer_type` is `INTERNAL`.",  # noqa: E501
    )
    amount = StrictPositiveInt64Field(help_text="Transfer amount in IRR (strictly positive int64 integer).")
    currency = serializers.CharField(
        max_length=3,
        help_text="Must be 'IRR'.",
    )
    occurred_at = serializers.DateTimeField(
        help_text="ISO-8601 UTC timestamp of the transaction.",
    )

    def validate_currency(self, value: str) -> str:
        """
        Field-level hook in DRF: automatically called for the `currency` field.
        """
        if value != "IRR":
            raise serializers.ValidationError("Only 'IRR' currency is supported.")
        return value

    def validate_occurred_at(self, value):
        """
        Ensure timestamp includes timezone info and is normalized to UTC (GEN-05).
        """
        raw_value = self.initial_data.get("occurred_at")
        if isinstance(raw_value, str):
            parsed = parse_datetime(raw_value)
            if parsed is not None and (parsed.tzinfo is None or parsed.tzinfo.utcoffset(parsed) is None):
                raise serializers.ValidationError(
                    "occurred_at must include explicit timezone information (e.g., 'Z' or '+00:00')."
                )
        return value.astimezone(UTC)

    def validate_destination_iban(self, value: str | None) -> str | None:
        if value is not None and not value.isascii():
            raise serializers.ValidationError("IBAN must contain only ASCII characters.")
        return value

    def validate(self, attrs: dict) -> dict:
        transfer_type = attrs.get("transfer_type")
        source_account_id = attrs.get("source_account_id")
        destination_account_id = attrs.get("destination_account_id")
        destination_iban = attrs.get("destination_iban")

        if transfer_type == TransferType.INTERNAL:
            if destination_account_id is None:
                raise serializers.ValidationError(
                    {"destination_account_id": "destination_account_id is required for INTERNAL transfers."}
                )
            if destination_iban is not None:
                raise serializers.ValidationError(
                    {"destination_iban": "destination_iban must be null or omitted for INTERNAL transfers."}
                )
            if source_account_id == destination_account_id:
                raise serializers.ValidationError(
                    {"destination_account_id": "Source and destination accounts cannot be identical."}
                )

        elif transfer_type == TransferType.EXTERNAL:
            if not destination_iban:
                raise serializers.ValidationError(
                    {"destination_iban": "destination_iban is required for EXTERNAL transfers."}
                )
            if destination_account_id is not None:
                raise serializers.ValidationError(
                    {"destination_account_id": "destination_account_id must be null or omitted for EXTERNAL transfers."}
                )

        return attrs


class DecisionReasonResponseSerializer(serializers.Serializer):
    """
    Output contract for a single reason item.
    """

    code = serializers.CharField()
    message = serializers.CharField()
    rule_id = serializers.UUIDField(required=False, allow_null=True)
    rule_revision = serializers.IntegerField(required=False, allow_null=True)
    rule_snapshot = serializers.JSONField(required=False, allow_null=True)

    def to_representation(self, instance):
        """
        Matches the exact Section 6 sample output for POST while keeping snapshot fields
        available when present.
        """
        data = {
            "code": instance.code,
            "message": instance.message,
        }
        if instance.rule_id is not None:
            data["rule_id"] = str(instance.rule_id)
        if instance.rule_revision is not None:
            data["rule_revision"] = instance.rule_revision
        if instance.rule_snapshot is not None:
            data["rule_snapshot"] = instance.rule_snapshot
        return data


class RiskAssessmentResponseSerializer(serializers.Serializer):
    """
    Output contract for POST /api/v1/risk-assessments (201 Created)
    and GET /api/v1/risk-assessments/{decision_id} (200 OK)
    """

    decision_id = serializers.UUIDField()
    transaction_id = serializers.UUIDField()
    decision = serializers.ChoiceField(choices=["APPROVE", "REJECT", "REVIEW"])
    evaluated_at = serializers.DateTimeField()
    reasons = DecisionReasonResponseSerializer(many=True)


class RiskAssessmentDetailResponseSerializer(RiskAssessmentResponseSerializer):
    """
    Extend output contract for GET /api/v1/risk-assessments/{decision_id}
    including transaction context and snapshot details.
    """

    transfer_type = serializers.ChoiceField(choices=TransferType.choices)
    source_account_id = serializers.UUIDField()
    destination_account_id = serializers.UUIDField(allow_null=True)
    destination_iban = serializers.CharField(allow_null=True)
    amount = serializers.IntegerField(min_value=1, max_value=MAX_INT64)
    currency = serializers.CharField()
    occurred_at = serializers.DateTimeField()
